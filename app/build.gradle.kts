android {
    namespace = "app.timiao.et"
    compileSdk = 35

    defaultConfig {
        applicationId = "app.timiao.et"
        minSdk = 26
        targetSdk = 35
        versionCode = 1
        versionName = "0.1.0"
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
        vectorDrawables.useSupportLibrary = true
        // The kernel .so is built only for these ABIs; drop other ABIs that libraries bring in.
        ndk { abiFilters += listOf("arm64-v8a", "x86_64") }
    }

    // Release signing: keystore lives outside the repo. Point TIMIAO_SIGNING at a .properties file
    // (storeFile, storePassword, keyAlias, keyPassword). Without it, release stays unsigned.
    val signingProps = System.getenv("TIMIAO_SIGNING")?.let { file(it) }?.takeIf { it.exists() }?.let { f ->
        Properties().apply { f.inputStream().use { stream -> load(stream) } }
    }
    signingConfigs {
        if (signingProps != null) {
            create("release") {
                storeFile = file(signingProps.getProperty("storeFile"))
                storePassword = signingProps.getProperty("storePassword")
                keyAlias = signingProps.getProperty("keyAlias")
                keyPassword = signingProps.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            if (signingProps != null) signingConfig = signingConfigs.getByName("release")
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro",
            )
        }
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    kotlinOptions {
        jvmTarget = "17"
    }

    packaging {
        resources.excludes += setOf("/META-INF/{AL2.0,LGPL2.1}")
    }
}

